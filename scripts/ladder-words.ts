// Builds src/games/ladder/words.ts from the raw word lists (see the header it
// writes for sources). Usage:
//   mise exec -- pnpm exec tsx scripts/ladder-words.ts ENABLE.txt SCOWL35.txt SCOWL50.txt ZIPF.txt
// ENABLE: https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
// SCOWL:  http://app.aspell.net/create?max_size=<35|50>&spelling=AU&max_variant=0
//         &diacritic=strip&download=wordlist&encoding=utf-8&format=inline
// ZIPF.txt has one "word zipf-frequency" line per SCOWL35 word, made once with
// wordfreq (`uv run --with wordfreq`):
//   from wordfreq import zipf_frequency
//   for w in words: print(w, f"{zipf_frequency(w, 'en'):.2f}")
import { readFileSync, writeFileSync } from "node:fs";

const LEN = 4;
/** Zipf frequency (log10 of occurrences per billion words) a start or target needs. */
const MIN_ZIPF = 3.5;

// Left out of both lists: words that shouldn't turn up in a daily puzzle.
const BLOCKED = new Set(
  (
    "anus arse arses butt cock coon crap cunt dick dyke fags fuck gook " +
    "homo jizz kike nazi paki piss porn poon rape scum sexy shit slut spic tits turd " +
    "twat wank whor"
  ).split(" "),
);

const [enablePath, common35Path, valid50Path, zipfPath] = process.argv.slice(2);
if (!enablePath || !common35Path || !valid50Path || !zipfPath) {
  throw new Error("usage: ladder-words.ts ENABLE.txt SCOWL35.txt SCOWL50.txt ZIPF.txt");
}

function words(path: string): string[] {
  return readFileSync(path, "utf8")
    .split("\n")
    .map((w) => w.trim())
    .filter((w) => w.length === LEN && /^[a-z]+$/.test(w) && !BLOCKED.has(w));
}

const valid = new Set([...words(enablePath), ...words(valid50Path)]);
const zipf = new Map(
  readFileSync(zipfPath, "utf8")
    .split("\n")
    .map((line) => line.split(" "))
    .map(([w, z]) => [w, Number(z)] as const),
);
const common = new Set(
  words(common35Path).filter((w) => valid.has(w) && (zipf.get(w) ?? 0) >= MIN_ZIPF),
);

function block(list: Iterable<string>): string {
  const sorted = [...list].toSorted();
  const lines: string[] = [];
  for (let i = 0; i < sorted.length; i += 14) lines.push(sorted.slice(i, i + 14).join(" "));
  return lines.join("\n");
}

const out = `// Word lists for Ladder. Generated by scripts/ladder-words.ts; do not edit.
//
// Provenance and licences:
// - VALID (any word may be a stepping stone): the union of
//   - ENABLE (Enhanced North American Benchmark Lexicon), public domain,
//     https://github.com/dolph/dictionary/blob/master/enable1.txt
//   - SCOWL / ESDB size 50, Australian spelling, variant level 0, generated at
//     http://app.aspell.net/create. Permissive licence (Kevin Atkinson, with
//     Australian data copyright 2016 Benjamin Titze: copy, modify and
//     distribute freely provided the copyright notices are kept; the primary
//     sources, 12dicts and ENABLE2K, are public domain).
// - COMMON (starts and targets): the SCOWL size 35 list (same settings and
//   licence), restricted to words that are also in VALID and have a wordfreq
//   Zipf frequency of at least 3.5. wordfreq (Robyn Speer et al.,
//   https://github.com/rspeer/wordfreq) is Apache-2.0 code over data under
//   CC BY-SA 4.0; only the selection of words above that threshold is used
//   here, so treat COMMON as carrying that attribution and share-alike.
// Only lowercase a-z words of four letters are kept, and a short blocklist of
// crude words is removed from both lists.

const VALID_WORDS = \`
${block(valid)}
\`;

const COMMON_WORDS = \`
${block(common)}
\`;

const split = (s: string) => s.split(/\\s+/).filter(Boolean);

export const VALID: ReadonlySet<string> = new Set(split(VALID_WORDS));
/** Sorted, so a puzzle's pick depends only on the RNG. */
export const COMMON: readonly string[] = split(COMMON_WORDS);
`;

writeFileSync(new URL("../src/games/ladder/words.ts", import.meta.url), out);
console.log(`valid ${valid.size}, common ${common.size}`);
